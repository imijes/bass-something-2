"""Bass Something 2's factory patches: a Bass Station II bank file (bs2/presets/factory.syx, its first 32 dumps: patch 0 into
P01 ... 31 into P32) as bs2/presets/presets.h, the table app.c's bank_factory reads through bsx_import at first
power-on (or a wiped store). Run it again when factory.syx changes:

    python3 bs2/presets/make_presets.py"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
NSLOTS, LEN = 32, 154


def main():
    d = (HERE / "factory.syx").read_bytes()
    dumps = [d[i:i + LEN] for i in range(0, len(d), LEN)]
    if len(d) % LEN or len(dumps) < NSLOTS or any(x[0] != 0xF0 or x[-1] != 0xF7 for x in dumps):
        raise SystemExit("factory.syx: not 32 Bass Station II dumps (154 bytes each, with a name)")
    out = ["/* generated by bs2/presets/make_presets.py from factory.syx: do not edit */",
           "/* ULTIMATE PATCHES Volume 2, its first 32 (credited in bs2/docs/MANUAL.md, Credits) */",
           "/* the factory patches: each a Bass Station II dump without its F0 and F7, as app_sysex has one */",
           f"static const uint8_t PRESETS[{NSLOTS}][{LEN - 2}] = {{"]
    for k, x in enumerate(dumps[:NSLOTS]):
        name = x[137:153].rstrip(b"\0 ").decode("ascii", "replace")
        out.append(f"    {{   /* P{k + 1:02d} {name} */")
        body = x[1:-1]
        for i in range(0, len(body), 16):
            out.append("        " + " ".join(f"0x{v:02X}," for v in body[i:i + 16]))
        out.append("    },")
    out.append("};")
    (HERE / "presets.h").write_text("\n".join(out) + "\n")
    print(f"presets.h: {NSLOTS} patches")


if __name__ == "__main__":
    main()
