#!/usr/bin/env python3
"""The first-boot demo, "i've used up 94% of my usage tokens", from a backup of an FM-1 (tools/fm1_backup.py backup
F --magic BS2B): its P01 (the patch and the sequence in it) and its drum pattern 00 (with the drums' levels, tunings,
master and tempo) -> demo.h, for app.c and bs2_dseq.c.

    python3 bs2/presets/make_demo.py BACKUP.bs2
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "..", "tools"))
import fm1_backup  # noqa: E402

OBJ_PATCHES, OBJ_DQ0, NDQ = 3, 5, 5          # app.h's OBJ_* (DQ0..DQ4: dq_mem_t, in slices)
NDT, NPAT = 13, 99                            # bs2_dseq.c's
TITLE = "i've used up 94% of my usage tokens"


def c_bytes(b):
    return ",\n".join("    " + ", ".join(f"0x{v:02X}" for v in b[i:i + 16]) for i in range(0, len(b), 16))


def main(path):
    with open(path, "rb") as f:
        image, _ = fm1_backup.split(f.read())
    _, objs = fm1_backup.parse(image)
    objs = dict(objs)
    bank = objs[OBJ_PATCHES]
    magic, version, nslots, psize = struct.unpack_from("<IHBB", bank)
    patch = bank[8:8 + psize]

    dq = b"".join(objs[OBJ_DQ0 + i] for i in range(NDQ))
    vol, tune = dq[4:4 + NDT], dq[4 + NDT:4 + 2 * NDT]
    metro, master, tempo = dq[4 + 2 * NDT:7 + 2 * NDT]
    pat0 = 36                                 # (dq_mem_t: magic, vol, tune, metro, master, tempo, used, then pat[])
    ln, start, n, prog, num, beat, meas, swing, ec = struct.unpack_from("<IHHHBBBBB", dq, pat0)
    ev0 = pat0 + NPAT * 16
    hits = struct.unpack_from(f"<{n}I", dq, ev0 + 4 * start)

    out = [
        f"/* the first-boot demo, \"{TITLE}\": generated by make_demo.py from a backup of the author's FM-1 */",
        f"#define DEMO_BANK_VERSION {version}u",
        f"#define DEMO_PSIZE {psize}u",
        f"static const uint8_t DEMO_PATCH[{psize}] = {{  /* P01, as bank_t keeps it (its sequence in it) */",
        c_bytes(patch), "};",
        "static const uint8_t DEMO_DT_VOL[NDT] = {" + ", ".join(str(v) for v in vol) + "};",
        "static const uint8_t DEMO_DT_TUNE[NDT] = {" + ", ".join(str(v) for v in tune) + "};",
        f"#define DEMO_DT_MASTER {master}u",
        f"#define DEMO_DT_TEMPO {tempo}u",
        f"static const dq_pat_t DEMO_PAT = {{.len = {ln}u, .start = 0, .n = {n}, .prog = 0x{prog:04X}u, .num = {num}, "
        f".beat = {beat}, .meas = {meas}, .swing = {swing}, .ec = {ec}}};",
        f"static const uint32_t DEMO_HITS[{n}] = {{  /* pattern 00's, in time order */",
        ",\n".join("    " + ", ".join(f"0x{h:08X}u" for h in hits[i:i + 6]) for i in range(0, n, 6)), "};", ""]
    with open(os.path.join(HERE, "demo.h"), "w") as f:
        f.write("\n".join(out))
    print(f"demo.h: P01 {psize} B (bank version {version}), pattern 00 {n} hits, {meas} bars, tempo {tempo}, "
          f"master {master}")


if __name__ == "__main__":
    main(sys.argv[1])
