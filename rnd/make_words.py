"""The RND Synth's patch names: BIP39's English word list (bs2/rnd/bip39_english.txt, from
https://github.com/bitcoin/bips/blob/master/bip-0039/english.txt, MIT licence), the list RND pixels names seeds with,
packed as bs2/rnd/words.h for bs2_rnd.c: each word its length (4 bits) and its letters (5 bits each, a = 1), bit by
bit from the first byte's lowest; WORD_AT[i] the bit where word 64 i starts. Run it again if the list changes:

    python3 bs2/rnd/make_words.py"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
EVERY = 64


def main():
    words = (HERE / "bip39_english.txt").read_text().split()
    if len(words) != 2048 or any(not (3 <= len(w) <= 8 and w.isalpha() and w.islower()) for w in words):
        raise SystemExit("bip39_english.txt: not BIP39's 2048 lowercase words of 3 to 8 letters")
    bits, at = [], []
    for i, w in enumerate(words):
        if i % EVERY == 0:
            at.append(len(bits))
        for v, n in [(len(w), 4)] + [(ord(c) - 96, 5) for c in w]:
            bits += [v >> b & 1 for b in range(n)]
    data = [sum(bit << j for j, bit in enumerate(bits[i:i + 8])) for i in range(0, len(bits), 8)]
    out = ["/* generated by bs2/rnd/make_words.py from bip39_english.txt (BIP39, MIT licence): do not edit */",
           f"/* BIP39's English words, packed: {len(data)} bytes */",
           f"#define WORD_EVERY {EVERY}u",
           "static const uint16_t WORD_AT[] = {" + ", ".join(map(str, at)) + "};",
           "static const uint8_t WORD_BITS[] = {"]
    out += ["    " + " ".join(f"0x{b:02X}," for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    out.append("};")
    (HERE / "words.h").write_text("\n".join(out) + "\n")
    print(f"words.h: {len(data)} bytes + {2 * len(at)} index")


if __name__ == "__main__":
    main()
